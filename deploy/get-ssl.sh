#!/usr/bin/env bash
set -e

SCRIPT_DIR=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
ROOT_DIR=$(cd "$SCRIPT_DIR/.." && pwd)
ENV_PATH="$ROOT_DIR/.env"

if [ ! -f "$ENV_PATH" ]; then
  echo ".env ?? ??????. ????????? ??????? deploy/install.sh"
  exit 1
fi

PANEL_DOMAIN=$(grep -E '^PANEL_DOMAIN=' "$ENV_PATH" | tail -n1 | cut -d= -f2-)
PANEL_DOMAIN=${PANEL_DOMAIN:-":80"}

if [ "$PANEL_DOMAIN" = ":80" ] || [ -z "$PANEL_DOMAIN" ]; then
  echo "????? ?? ????? (PANEL_DOMAIN). SSL ?? ????????? ??? ??????? ?? IP."
  exit 0
fi

if docker compose version >/dev/null 2>&1; then
  DC="docker compose"
elif command -v docker-compose >/dev/null 2>&1; then
  DC="docker-compose"
else
  echo "Docker Compose ?? ??????."
  exit 1
fi

echo "???????? Caddy ??? ????????? SSL ??????????? ??? ?????? $PANEL_DOMAIN..."
cd "$ROOT_DIR"
$DC up -d caddy

echo "?????? ?????? ??????????? (?? 2 ?????)..."
END=$((SECONDS + 120))
while [ $SECONDS -lt $END ]; do
  if $DC logs --tail=50 caddy 2>/dev/null | grep -qi "certificate obtained"; then
    echo "?????????? ??????? ???????."
    exit 0
  fi
  sleep 5
done

echo "?? ??????? ????????? ????????? ???????????."
echo "????????? DNS ? ??????????? ?????? 80/443, ????? ?????????? ?????."
exit 1
